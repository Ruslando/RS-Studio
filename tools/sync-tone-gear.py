"""Generate the shared Rocksmith catalogue from a pinned Rocksmith2014.NET checkout.

Usage: python tools/sync-tone-gear.py SOURCE_DIR REVISION
SOURCE_DIR contains tone_gear_data.json and ToneDescriptors.fs from that revision.
This is an offline build step; the app never downloads device definitions.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    source, revision = Path(sys.argv[1]), sys.argv[2]
    if not re.fullmatch(r"[a-f0-9]{40}", revision):
        raise ValueError("A full upstream commit SHA is required")
    raw = (source / "tone_gear_data.json").read_bytes()
    gear = json.loads(raw.decode("utf-8-sig"))
    descriptors = [dict(Name=name, UIName=ui) for name, ui in re.findall(
        r'Name = "([^"]+)".*?UIName = "([^"]+)"',
        (source / "ToneDescriptors.fs").read_text(encoding="utf-8-sig"), re.S)]
    assert len(gear) == len({entry["Key"] for entry in gear})
    assert len(descriptors) >= 25
    assert all(knob.get("DefaultValue") is not None for entry in gear for knob in entry.get("Knobs") or []), "every knob needs a native default"
    catalog = {"Source": "Rocksmith2014.NET / DLC Builder", "Revision": revision,
               "URL": f"https://github.com/iminashi/Rocksmith2014.NET/tree/{revision}",
               "License": "MIT", "SourceSHA256": hashlib.sha256(raw).hexdigest(),
               "Gear": gear, "Descriptors": descriptors}
    data = json.dumps(catalog, ensure_ascii=False, separators=(",", ":"))
    (ROOT / "src/rs_studio/rocksmith/res/tone-gear.json").write_text(data + "\n", encoding="utf-8")
    (ROOT / "web/tone-gear.js").write_text(
        "// Generated by tools/sync-tone-gear.py; do not edit.\n"
        "// Rocksmith2014.NET, Copyright (c) 2020 Tapio Malmberg, MIT.\n"
        "// See licenses/Rocksmith2014.NET-LICENSE.txt and NOTICE.\n"
        "export const TONE_CATALOG = " + data + ";\n", encoding="utf-8")
    print(f"Generated {len(gear)} gear definitions and {len(descriptors)} tone descriptors")


if __name__ == "__main__":
    main()
