import assert from 'node:assert/strict';
import { configureSaveState, isDirty, markSaved, refreshSaveState, withoutDirtying } from '../../web/save-state.js';

const S = { state: { job: 'song', name: 'Song' } };
const controls = Object.fromEntries(['projTab', 'projTabName', 'projDirtyDot', 'saveBtn', 'saveAsBtn'].map(key => [key, {}]));
const body = { editLanes: [{ notes: [] }], grid: { bpm: 120 }, mix: {}, view: { zoomX: 1 } };
configureSaveState({ S, projectBody: () => body, projectName: state => state.name, ...controls });
markSaved();
assert.equal(isDirty(), false);
assert.equal(controls.projTabName.textContent, 'Song');
body.view.zoomX = 4;
assert.equal(isDirty(), false, 'view changes do not dirty saved content');
withoutDirtying(before => { before(); body.editLanes[0].notes.push({ pitch: 60, pos: { string: 1, fret: 1 } }); return true; });
assert.equal(isDirty(), false, 'automatic placement preserves a clean baseline');
body.grid.bpm = 130;
refreshSaveState();
assert.equal(controls.projDirtyDot.hidden, false);
withoutDirtying(before => { before(); body.editLanes[0].notes[0].pos.fret = 2; return true; });
assert.equal(isDirty(), true, 'automatic placement never clears existing edits');
markSaved();
body.mix.notes = .5;
assert.equal(isDirty(), true, 'mixer settings are saved content');
markSaved();
withoutDirtying(() => false);
assert.equal(isDirty(), false, 'a no-op does not change save state');
S.state.job = 'tutorial';
body.grid.bpm = 140;
refreshSaveState();
assert.equal(isDirty(), false);
assert.equal(controls.saveBtn.disabled, true);
assert.equal(controls.saveAsBtn.disabled, true);
S.state = null;
markSaved();
assert.equal(controls.projTab.hidden, true);
assert.equal(isDirty(), false);
