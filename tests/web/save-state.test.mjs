import assert from 'node:assert/strict';
import { acceptSavedAudio, configureSaveState, isDirty, markSaved, refreshSaveState, withoutDirtying } from '../../web/save-state.js';

const S = { state: { job: 'song', name: 'Song' } };
const controls = Object.fromEntries(['projTab', 'projTabName', 'projDirtyDot', 'saveBtn', 'saveAsBtn'].map(key => [key, {}]));
const body = { editLanes: [{ notes: [] }], grid: { bpm: 120 }, mix: {}, view: { zoomX: 1 } };
configureSaveState({ S, projectBody: () => body, projectName: state => state.name, ...controls });
markSaved();
assert.equal(isDirty(), false);
assert.equal(controls.projTabName.textContent, 'Song');
body.view.zoomX = 4;
assert.equal(isDirty(), false, 'view changes do not dirty saved content');
withoutDirtying(before => { before(); body.editLanes[0].notes.push({ pitch: 60, pos: { string: 1, fret: 1 } }); return true; });
assert.equal(isDirty(), false, 'automatic placement preserves a clean baseline');
body.grid.bpm = 130;
refreshSaveState();
assert.equal(controls.projDirtyDot.hidden, false);
withoutDirtying(before => { before(); body.editLanes[0].notes[0].pos.fret = 2; return true; });
assert.equal(isDirty(), true, 'automatic placement never clears existing edits');
markSaved();
body.mix.notes = .5;
assert.equal(isDirty(), true, 'mixer settings are saved content');
markSaved();
withoutDirtying(() => false);
assert.equal(isDirty(), false, 'a no-op does not change save state');
body.editLanes[0].active = true;
assert.equal(isDirty(), false, 'active layer is workspace state');
body.comments = [{ t: 1, text: 'Remember this' }];
assert.equal(isDirty(), true, 'comments require a project save');
markSaved();
body.metadata = { rocksmith: { ignoredIssues: ['I01'] } };
assert.equal(isDirty(), true, 'diagnostic ignore choices require a project save');
markSaved();
const snapshot = structuredClone(body);
body.editLanes[0].notes[0].pitch = 65;
markSaved(snapshot);
assert.equal(isDirty(), true, 'edits made while a save is in flight remain unsaved');
body.stemSettings = [{ id: 'new-audio', volume: 1, muted: false }];
acceptSavedAudio(body.stemSettings);
assert.equal(isDirty(), true, 'uploading audio never clears pending note edits');
body.editLanes[0].notes[0].pitch = snapshot.editLanes[0].notes[0].pitch;
assert.equal(isDirty(), false, 'the new audio asset itself is already saved');
body.stemSettings.push({ id: 'other-audio', volume: 1, muted: false });
markSaved();
body.stemSettings.reverse();
assert.equal(isDirty(), true, 'audio order requires a project save');
S.state.job = 'tutorial';
body.grid.bpm = 140;
refreshSaveState();
assert.equal(isDirty(), false);
assert.equal(controls.saveBtn.disabled, true);
assert.equal(controls.saveAsBtn.disabled, true);
S.state = null;
markSaved();
assert.equal(controls.projTab.hidden, true);
assert.equal(isDirty(), false);
